// Regenerates paramdata.js (mock parameter tables) from research/raw/param_dumps and probe_PA_files_env.json.
//   node bridge/tests/mocks/gen-paramdata.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const raw = join(here, '..', '..', '..', 'research', 'raw');
const load = (p) => JSON.parse(readFileSync(join(raw, p), 'utf8'));

const VEC_SIZE = { Vec2D: 2, Vec3D: 3, Vec4D: 4 };

// Dumps print host vectors as [object CallbackObject]; fall back to neutral defaults.
function defaultFor(p) {
  const v = p.v;
  const n = VEC_SIZE[p.t];
  if (n) {
    if (v && v.x !== undefined) return ['x', 'y', 'z', 'w'].slice(0, n).map((k) => v[k]);
    const base = p.n === 'scale' || p.n === 'UVScale' || p.n === 'shadingScale' ? 1 : 0;
    return p.t === 'Vec4D' ? [1, 1, 1, 1] : new Array(n).fill(base);
  }
  if (p.t === 'unknown') {
    if (v && v.unreadable) return { unreadable: true };
    return p.n === 'resolution' ? [640, 480] : null;
  }
  if (p.t === 'Texture') return '';
  if (p.t === 'Link') return null;
  return v;
}

const table = (params) => params.map((p) => [p.n, p.t, defaultFor(p)]);

const objects = load('param_dumps/objects.json');
const tags = load('param_dumps/tags.json');
const misc = load('param_dumps/camera_renderer_materials_nodes.json');
const env = load('probe_PA_files_env.json').result;

const out = {
  consts: env.consts,
  missing: env.missing,
  objects: Object.fromEntries(Object.entries(objects).map(([k, o]) => [k, { name: o.name, family: o.family, type: o.type, hasCore: o.hasCore, params: table(o.params) }])),
  // PROPWINTAG could not be created by the dump script (null entry).
  tags: Object.fromEntries(Object.entries(tags).filter(([, t]) => t && t.params).map(([k, t]) => [k, { type: t.type, family: t.family, params: table(t.params) }])),
  renderer: table(misc.renderer),
  material: table(misc.material),
  rootNode: { type: misc.rootNode.type, ins: misc.rootNodeIO.inputs.length, outs: 0, params: table(misc.rootNode.params) },
  nodes: Object.fromEntries(Object.entries(misc.nodes).map(([k, n]) => [k, { ins: n.ins, outs: n.outs, params: table(n.params) }])),
};

writeFileSync(join(here, 'paramdata.js'), `// Generated by gen-paramdata.mjs from research/raw - do not edit.\nvar __PARAMDATA = ${JSON.stringify(out)};\n`);
console.log('paramdata.js written');
