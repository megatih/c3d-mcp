#!/usr/bin/env node
// Generates docs/TOOLS.md from the zod schemas of the compiled tools (run `npm run build` first).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { z } from 'zod';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const dist = path.join(pkg, 'dist', 'tools', 'index.js');
if (!fs.existsSync(dist)) {
  console.error('dist/ not found: run `npm run build` in packages/server first.');
  process.exit(1);
}
const { allTools, allPrompts, allResources } = await import(pathToFileURL(dist).href);
const out = path.resolve(pkg, '..', '..', 'docs', 'TOOLS.md');

const typeOf = (s) => {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(' \\| ');
  const alts = s.anyOf ?? s.oneOf;
  if (alts) return [...new Set(alts.map(typeOf))].join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.type === 'object' && s.properties) return 'object';
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  const t = Array.isArray(s.type) ? s.type.join('|') : (s.type ?? 'any');
  const b = [s.minimum !== undefined && `>=${s.minimum}`, s.maximum !== undefined && `<=${s.maximum}`, s.maxLength !== undefined && `len<=${s.maxLength}`].filter(Boolean);
  return b.length ? `${t} (${b.join(', ')})` : t;
};
const esc = (s = '') => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

const groups = new Map();
for (const t of allTools) (groups.get(t.group) ?? groups.set(t.group, []).get(t.group)).push(t);

let md = `# c3d-mcp tool reference\n\n> Generated by \`packages/server/scripts/gen-tool-docs.mjs\` from the zod schemas. Do not edit by hand.\n> Health tools (\`c3d_doctor\`, \`c3d_install_bridge\`, \`c3d_capabilities\`) are documented with the server core.\n\n`;
md += `${allTools.length} tools (+3 health tools = ${allTools.length + 3}). R = read-only, W = mutating, W! = destructive. Profiles: full / local (small curated set for local models) / readonly.\n\n## Index\n\n| Tool | Group | R/W | Profiles | Summary |\n|---|---|---|---|---|\n`;
for (const t of allTools) md += `| [\`${t.name}\`](#${t.name}) | ${t.group} | ${t.mutating ? (t.destructive ? 'W!' : 'W') : 'R'} | ${t.profiles.join(', ')} | ${esc(t.title)} |\n`;
for (const [group, tools] of groups) {
  md += `\n## Group: ${group}\n`;
  for (const t of tools) {
    const input = z.toJSONSchema(t.inputSchema, { io: 'input' });
    const output = z.toJSONSchema(t.outputSchema, { io: 'output' });
    md += `\n### ${t.name}\n\n**${t.title}** - ${t.mutating ? (t.destructive ? 'writes, destructive' : 'writes') : 'read-only'}${t.idempotent ? ', idempotent' : ''}${t.openWorld ? ', open-world (network)' : ''}. Profiles: ${t.profiles.join(', ')}.\n\n${t.description}\n\n`;
    if (t.localDescription) md += `Local profile hint: _${t.localDescription}_\n\n`;
    const req = new Set(input.required ?? []);
    const props = Object.entries(input.properties ?? {});
    if (props.length) {
      md += `| Parameter | Type | Required | Description |\n|---|---|---|---|\n`;
      for (const [k, v] of props) md += `| \`${k}\` | ${typeOf(v)} | ${req.has(k) ? 'yes' : 'no'} | ${esc(v.description)} |\n`;
    } else md += `No parameters.\n`;
    const oprops = Object.entries(output.properties ?? {});
    md += `\n**Output fields:** ${oprops.length ? oprops.map(([k, v]) => `\`${k}\`${v.type ? ` (${typeOf(v)})` : ''}`).join(', ') : '(free-form)'}\n`;
  }
}
md += `\n## Prompts\n\n| Name | Arguments | Description |\n|---|---|---|\n`;
for (const p of allPrompts) md += `| \`${p.name}\` | ${Object.keys(p.args).join(', ')} | ${esc(p.description)} |\n`;
md += `\n## Resources\n\n| URI | Description |\n|---|---|\n`;
for (const r of allResources) md += `| \`${r.uri}\` | ${esc(r.description)} |\n`;
md += `\n## Health tools (always available)\n\n| Tool | R/W | What it does |\n|---|---|---|\n| \`c3d_doctor\` | R | Structured health checks (Cheetah3D, bridge, helper, permissions, ping, dialogs) with a fix per failing check. |\n| \`c3d_install_bridge\` | W | Idempotent install of the bridge macro, runtime and helper app (backs up Scripts/ first); a Cheetah3D restart is needed once. Input: \`skip_ping\` (boolean). |\n| \`c3d_capabilities\` | R | Runtime type map (object/tag/material/node types, light types, formats, limits) and the active profile's tool list. |\n`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
console.log(`wrote ${out} (${allTools.length} tools)`);
