import { connect } from './live-driver.mjs';
import { mkdtempSync } from 'node:fs'; import { tmpdir } from 'node:os'; import { join } from 'node:path';
const { call, close } = await connect();
const tmp = mkdtempSync(join(tmpdir(), 'c3dlive-'));
let bad = 0; const results = [];
const step = async (label, name, args = {}, { expectErr = false, show = false } = {}) => {
  let r; try { r = await call(name, args); } catch (e) { r = { ms: 0, isError: true, sc: { exception: String(e) } }; }
  const ok = expectErr ? r.isError : !r.isError; if (!ok) bad++;
  console.log(`${ok ? 'ok  ' : 'FAIL'} ${label} [${name}] ${r.ms}ms${ok && !show ? '' : ' ' + JSON.stringify(r.sc ?? r.text).slice(0, 500)}`);
  results.push(r); return r;
};
const id = (r) => r.sc?.object?.id ?? r.sc?.ref?.id ?? r.sc?.id;
await step('new doc', 'c3d_new_document');
await step('caps', 'c3d_capabilities');
await step('docs', 'c3d_search_api_docs', { query: 'addIndexPolygon' });
const top = await step('top', 'c3d_create_object', { type: 'BOX', name: 'Top', position: { x: 0, y: 1, z: 0 }, scale: { x: 1, y: 0.1, z: 1 } });
const legs = [];
for (const [i, [x, z]] of [[-.9, -.9], [.9, -.9], [-.9, .9], [.9, .9]].entries()) legs.push(await step('leg' + i, 'c3d_create_object', { type: 'BOX', name: 'Leg' + i, position: { x, y: .5, z }, scale: { x: .1, y: .5, z: .1 } }));
const grp = await step('folder', 'c3d_create_object', { type: 'FOLDER', name: 'Table' });
for (const r of [top, ...legs]) await step('reparent', 'c3d_reparent', { ref: { id: id(r) }, parent: { id: id(grp) } });
await step('list', 'c3d_list_scene', { depth: 5 }, { show: true });
const mat = await step('material', 'c3d_create_material', { name: 'Wood', color: { r: .55, g: .35, b: .15, a: 1 } }, { show: true });
await step('assign', 'c3d_assign_material', { ref: { id: id(top) }, material: { name: mat.sc?.material?.name ?? 'Wood' } }, { show: true });
for (const l of legs) await step('assign leg', 'c3d_assign_material', { ref: { id: id(l) }, material: { name: mat.sc?.material?.name ?? 'Wood' } });
await step('light', 'c3d_set_light', { name: 'Key', light_type: 'point', position: { x: 3, y: 4, z: 3 }, intensity: 1, look_at_point: { x: 0, y: 0, z: 0 } }, { show: true });
const cam = await step('camera', 'c3d_set_camera', { name: 'Cam', position: { x: 3, y: 2, z: 4 }, look_at_point: { x: 0, y: .5, z: 0 }, fov: 45, active: true }, { show: true });
const cid = cam.sc?.camera?.id ?? cam.sc?.object?.id ?? cam.sc?.ref?.id; 
await step('get cam', 'c3d_get_object', { ref: { id: cid }, include: ['worldMatrix'] }, { show: true });
await step('look_at', 'c3d_look_at', { ref: { id: cid }, target_point: { x: 0, y: .5, z: 0 } }, { show: true });
await step('render', 'c3d_render_settings', {}, { expectErr: true });
await step('render settings', 'c3d_set_render_settings', { width: 320, height: 240 }, { show: true });
await step('render image', 'c3d_render_image', { path: join(tmp, 'a.png'), include_image: true }, { show: true });
await step('keyframes', 'c3d_set_keyframes', { ref: { id: id(top) }, param: 'position', keys: [{ time: 0, value: { x: 0, y: 1, z: 0 } }, { time: 1, value: { x: 0, y: 2, z: 0 } }] }, { show: true });
await step('get keys', 'c3d_get_keyframes', { ref: { id: id(top) }, param: 'position' }, { show: true });
await step('time', 'c3d_set_time', { time: 0.5 });
await step('get params', 'c3d_get_parameters', { ref: { id: id(top) }, names: ['position'] }, { show: true });
await step('time0', 'c3d_set_time', { time: 0 });
await step('takes', 'c3d_takes', { action: 'list' }, { show: true });
await step('mesh', 'c3d_create_mesh', { name: 'Tri', vertices: [[0,0,0],[1,0,0],[0,1,0],[1,1,0]], polygons: [[0, 1, 3, 2]] }, { show: true });
await step('bad mesh', 'c3d_create_mesh', { vertices: [[0, 0, 0], [1, 0, 0], [0, 1, 0]], polygons: [[0, 1, 7]] }, { expectErr: true });
await step('spline', 'c3d_create_spline', { name: 'Sp', paths: [{ points: [{ p: [0,0,0] }, { p: [1,0,1] }, { p: [2,0,0] }], closed: false }] }, { show: true });
await step('tag', 'c3d_add_tag', { ref: { id: id(top) }, type: 'SHADERTAG' }, { show: true });
await step('select', 'c3d_select', { refs: [{ id: id(top) }] });
await step('rename', 'c3d_rename', { ref: { id: id(top) }, name: 'TableTop' });
await step('transform', 'c3d_set_transform', { ref: { id: id(top) }, rotation: { x: 0, y: 45, z: 0 } }, { show: true });
await step('setparams', 'c3d_set_parameters', { ref: { id: id(top) }, params: { sizeX: 2 } }, { show: true });
await step('materials', 'c3d_list_materials', {});
await step('node', 'c3d_add_material_node', { material: { name: mat.sc?.material?.name ?? 'Wood' }, type: 'wood' }, { show: true });
await step('graph', 'c3d_get_material_graph', { material: { name: mat.sc?.material?.name ?? 'Wood' } });
await step('lint', 'c3d_lint_script', { code: 'function main(doc){ File.mkDir("/tmp/x"); }' }, { show: true });
await step('run', 'c3d_run_script', { code: 'var n=doc.root().childCount(); print("hi"); return n;' }, { show: true });
await step('checkpoint', 'c3d_checkpoint', { label: 'live' }, { show: true });
await step('export', 'c3d_export', { path: join(tmp, 'out.fbx'), format: 'fbx' }, { show: true });
await step('save', 'c3d_save_document', { path: join(tmp, 'doc.jas') }, { show: true });
await step('delete', 'c3d_delete_objects', { refs: [{ id: id(legs[0]) }] }, { show: true });
await step('console', 'c3d_get_console', { tail: 5 });
await close();
console.log(bad ? `${bad} FAILURES` : 'ALL OK', tmp);
