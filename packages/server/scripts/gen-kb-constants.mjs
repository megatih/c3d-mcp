// Regenerates src/services/kbConstants.generated.ts from research/raw/kb-constants-8.1.3.json (written by kb-constants-live.mjs).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const j = JSON.parse(readFileSync(join(here, '../../../research/raw/kb-constants-8.1.3.json'), 'utf8'));
const body = Object.entries(j.present).map(([k, v]) => `  ${k}: ${v},`).join('\n');
writeFileSync(join(here, '../src/services/kbConstants.generated.ts'), `// GENERATED by scripts/gen-kb-constants.mjs from research/raw/kb-constants-8.1.3.json (${j.app}); do not edit.
// Every ALL-CAPS identifier found in the vendored API docs, examples, gotchas and the app binary that exists at runtime, with its value.
export const VERIFIED_CONSTANTS: Readonly<Record<string, number>> = {
${body}
};
`);
console.log('constants:', Object.keys(j.present).length);
